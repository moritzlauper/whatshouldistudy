export const fitText = (locale: Locale) => copy[locale.startsWith('de') ? 'de' : locale.startsWith('fr') ? 'fr' : locale.startsWith('it') ? 'it' : 'en']

/** A band's grade range on its scale, worst grade first: «unter 4», «4–5», «5–6» in Swiss notation. */
export function bandText(band: GradeBand, scale: GradeScaleId, intl: string): string {
  const fmt = (x: number) => x.toLocaleString(intl, { maximumFractionDigits: 1 })
  const [from, to] = bandRange(band, scale)
  return `${fmt(from)}–${fmt(to)}`
}
