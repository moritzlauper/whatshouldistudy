export const fitText = (locale: Locale) => copy[locale.startsWith('de') ? 'de' : locale.startsWith('fr') ? 'fr' : locale.startsWith('it') ? 'it' : 'en']

/** A grade as written on its scale: one decimal on the 1 to 6 scales, whole numbers for percent. */
export function fmtGrade(value: number, scale: GradeScaleId, intl: string): string {
  return value.toLocaleString(intl, { maximumFractionDigits: scale === 'percent' ? 0 : 2 })
}
