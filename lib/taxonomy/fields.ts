/**
 * The field-of-study taxonomy everything else hangs off: the matcher scores
 * these fields, the scrapers sort every programme into them, and the field
 * pages describe them.
 *
 * Per field:
 * - riasec      Holland interest profile (Realistic, Investigative, Artistic,
 *               Social, Enterprising, Conventional), 0..1, modelled on O*NET
 *               interest profiles of the occupations the field leads to.
 * - big5        Small tilts (-0.5..0.5) for Openness, Conscientiousness,
 *               Extraversion, Agreeableness, Neuroticism, after the
 *               personality-and-major literature (e.g. Vedel 2016 meta-analysis).
 *               Deliberately weak: personality explains little of major choice.
 * - subjects    How much the field draws on each school subject, 0..1.
 * - values      What the field typically offers (salary, security, ...), 0..1.
 * - popularity  How common the topic is in everyday media consumption,
 *               relative (1 = average). The interest model compares a person's
 *               share against this baseline, so a little maths content says
 *               more than a little fitness content.
 * - cip / cah / isced / openalex  Codes used to sort programmes from the
 *               official data sources into the field.
 */

export type FieldGroup =
  | 'science'
  | 'computing'
  | 'engineering'
  | 'health'
  | 'social'
  | 'business'
  | 'humanities'
  | 'arts'
  | 'applied'

export const RIASEC_KEYS = ['R', 'I', 'A', 'S', 'E', 'C'] as const
export type RiasecKey = (typeof RIASEC_KEYS)[number]
export type Riasec = [number, number, number, number, number, number]

export const BIG5_KEYS = ['O', 'C', 'E', 'A', 'N'] as const
export type Big5Key = (typeof BIG5_KEYS)[number]
export type Big5 = Record<Big5Key, number>

export const SUBJECT_KEYS = [
  'math',
  'phys',
  'chem',
  'bio',
  'cs',
  'lang',
  'forlang',
  'hist',
  'geo',
  'econ',
  'art',
  'music',
  'sport',
  'social',
] as const
export type SubjectKey = (typeof SUBJECT_KEYS)[number]

export const VALUE_KEYS = [
  'salary',
  'security',
  'creativity',
  'helping',
  'tech',
  'outdoors',
  'autonomy',
  'impact',
] as const
export type ValueKey = (typeof VALUE_KEYS)[number]

export interface Field {
  id: string
  name: string
  group: FieldGroup
  blurb: string
  riasec: Riasec
  big5: Partial<Big5>
  subjects: Partial<Record<SubjectKey, number>>
  values: Record<ValueKey, number>
  popularity: number
  careers: string[]
  /** CIP 2020 prefixes (US); the first field listing a code is its primary home. */
  cip: string[]
  /** UK CAH prefixes (Discover Uni). */
  cah: string[]
  isced: string[]
  /** OpenAlex subfield ids (4 digits) or field ids (2 digits). */
  openalex: number[]
}

type V = [number, number, number, number, number, number, number, number]
const v = (x: V): Record<ValueKey, number> => ({
  salary: x[0],
  security: x[1],
  creativity: x[2],
  helping: x[3],
  tech: x[4],
  outdoors: x[5],
  autonomy: x[6],
  impact: x[7],
})

